"""Trunk-CoM / trunk-mass vs joint-offset disambiguation in the torque channel (numerical demo).

On a recorded Phase-2 calibration (samples_tau_<mode>_<seed>.npz, gated rows) and at the TRUE
parameters:
  1. per-sample torque-residual signatures (Fx Fy Fz Mx My Mz) of +1 deg along W1 (weakest
     loop-closure direction) and of the trunk parameters, binned by the true knee angle
     -> configuration dependence (offset signature varies with the leg geometry, trunk ~constant);
  2. linearised leakage ("confusion") with the white noise model of both channels:
       inject trunk_dx = +2.5 cm (no offset)  -> spurious offset estimate along W1
       inject trunk_dm = +0.8 kg              -> spurious W1
       inject 2 deg along W1 (true trunk)     -> spurious trunk_dx / trunk_dm
     using (a) one static pose (the 30 samples closest to the median knee angle) and
           (b) the whole trajectory; torque channel alone and with loop closure.
Usage: .venv/bin/python zero_torque_disamb.py [seed] [mode]   -> results/q0/torque_disamb_<mode>_<seed>.json
"""
import os, sys, json
import numpy as np
from scenarios import true_params_q0, PRIOR_STD
from zero_id import ZeroEstimator, NL, NP, NR
from zero_torque import TorqueChannel, prepare, whiten, NTR
from wbc import quat_to_mat

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "results", "q0")


def main(seed=0, mode="active"):
    tp = true_params_q0(seed)
    d_true = np.array(tp.q0[:NL]); tr_true = np.array([tp.trunk_dm, tp.trunk_dx, tp.trunk_dy, tp.trunk_dz])
    rec = np.load(os.path.join(OUT, f"samples_tau_{mode}_{seed}.npz"))
    pub = json.load(open(os.path.join(OUT, f"calib_{mode}_{seed}.json")))["free"]
    V = np.array(pub["eigvecs"]); W1 = V[:, 0]                       # weakest deployed LC direction
    idx = np.flatnonzero(rec["gated"])
    S = prepare(rec, idx)
    tc = TorqueChannel()
    R, J, C = tc.residuals(d_true, tr_true, [tp.frictionloss], S)
    _, Jw = whiten(R, J, C)                                          # (N,6,12+4+1)
    est = ZeroEstimator(use_tau=False)
    Q = rec["q"][idx, :NL]; Gb = np.array([quat_to_mat(q).T @ np.array([0, 0, 1.0]) for q in rec["quat"][idx]])
    th = np.zeros(NP); th[:NL] = d_true; th[NL:] = est.nominal_stance()
    _, Jl = est.residuals(th, Q, Gb); Jl = Jl / est.sig[None, :, None]  # (N,10,15)
    knee = np.rad2deg(0.5 * (rec["truth"][idx, 3] + rec["truth"][idx, 9]))
    N = len(idx)

    # ---------- 1. signatures vs knee angle (raw units: N, N m)
    sW1 = J[:, :, :NL] @ W1 * np.deg2rad(1.0)
    sdm = J[:, :, NL] * 0.1; sdx = J[:, :, NL + 1] * 0.01
    bins = np.quantile(knee, np.linspace(0, 1, 6))
    tab = []
    for a, b in zip(bins[:-1], bins[1:]):
        m = (knee >= a) & (knee <= b)
        tab.append(dict(knee=[round(float(a), 1), round(float(b), 1)], n=int(m.sum()),
                        W1_Fx=float(sW1[m, 0].mean()), W1_Fz=float(sW1[m, 2].mean()), W1_My=float(sW1[m, 4].mean()),
                        dm_Fz=float(sdm[m, 2].mean()), dx_My=float(sdx[m, 4].mean()), dx_Fz=float(sdx[m, 2].mean())))

    # ---------- 2. linearised leakage
    # parameter vector p = [delta(12), trunk(4), mu, nuis(3)]
    p = NL + NTR + 1 + 3
    pri = np.r_[np.zeros(NL), 1 / np.array([PRIOR_STD[k] for k in ("trunk_dm", "trunk_dx", "trunk_dy", "trunk_dz")]) ** 2,
                1 / PRIOR_STD["frictionloss"] ** 2, np.full(3, 1e-6)]
    pri[:NL] = 1 / np.deg2rad(2.0) ** 2                              # deployed prior on delta

    def leak(sel, use_lc, inj):
        Jt = np.zeros((len(sel), 6, p)); Jt[:, :, :NL + NTR + 1] = Jw[sel]
        A = [Jt.reshape(-1, p)]
        if use_lc:
            Jlc = np.zeros((len(sel), NR, p)); Jlc[:, :, :NL] = Jl[sel, :, :NL]; Jlc[:, :, -3:] = Jl[sel, :, NL:]
            A.append(Jlc.reshape(-1, p))
        A = np.vstack(A)
        y = A @ inj                                                  # noiseless data generated by inj
        est_ = np.linalg.solve(A.T @ A + np.diag(pri), A.T @ y)
        return dict(W1_deg=float(np.rad2deg(W1 @ est_[:NL])), dm_kg=float(est_[NL]), dx_cm=float(100 * est_[NL + 1]),
                    dy_cm=float(100 * est_[NL + 2]))

    def vec(trunk=None, wdeg=0.0):
        v = np.zeros(p)
        if trunk is not None:
            v[NL:NL + NTR] = trunk
        v[:NL] = W1 * np.deg2rad(wdeg)
        return v

    pose = np.argsort(np.abs(knee - np.median(knee)))[:30]
    allk = np.arange(N)
    out = dict(seed=seed, mode=mode, n=N, knee_range=[float(knee.min()), float(knee.max())],
               W1=[round(float(x), 3) for x in W1], signature_vs_knee=tab, leakage={})
    for nm, inj in (("trunk_dx+2.5cm", vec([0, 0.025, 0, 0])), ("trunk_dm+0.8kg", vec([0.8, 0, 0, 0])),
                    ("W1+2deg", vec(None, 2.0))):
        for sname, sel in (("one_pose", pose), ("trajectory", allk)):
            for lc in (False, True):
                out["leakage"][f"{nm}|{sname}|{'lc+tau' if lc else 'tau_only'}"] = leak(sel, lc, inj)
    return out


if __name__ == "__main__":
    seed = int(sys.argv[1]) if len(sys.argv) > 1 else 0
    mode = sys.argv[2] if len(sys.argv) > 2 else "active"
    o = main(seed, mode)
    json.dump(o, open(os.path.join(OUT, f"torque_disamb_{mode}_{seed}.json"), "w"), indent=1)
    print(f"seed {seed} {mode} n={o['n']} knee {o['knee_range'][0]:.1f}..{o['knee_range'][1]:.1f} deg")
    print("signature per +1 deg W1 / +0.1 kg / +1 cm dx, by knee-angle quintile:")
    for t in o["signature_vs_knee"]:
        print(f"  knee {t['knee'][0]:5.1f}-{t['knee'][1]:5.1f}  W1: Fx {t['W1_Fx']:+.3f} N Fz {t['W1_Fz']:+.3f} N My {t['W1_My']:+.4f} Nm"
              f" | dm: Fz {t['dm_Fz']:+.3f} N | dx: My {t['dx_My']:+.4f} Nm Fz {t['dx_Fz']:+.4f} N")
    print("linearised leakage (noiseless injection -> MAP with priors):")
    for k, v in o["leakage"].items():
        print(f"  {k:42s} W1 {v['W1_deg']:+7.3f} deg  dm {v['dm_kg']:+.3f} kg  dx {v['dx_cm']:+.3f} cm  dy {v['dy_cm']:+.3f} cm")
